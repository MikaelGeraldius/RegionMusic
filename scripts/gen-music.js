// Scans assets/music/{city,town,route}/ and writes src/music/tracks.generated.ts.
// Metro can only bundle files named in a static require(), so the list is generated.
// Run with `npm run music` after adding or removing songs (start/android/ios run it too).
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const musicDir = path.join(root, 'assets', 'music');
const outFile = path.join(root, 'src', 'music', 'tracks.generated.ts');
const KINDS = ['city', 'town', 'route'];
// Audio types Metro bundles by default (no ogg/flac: convert those to mp3).
const EXTS = ['.mp3', '.m4a', '.aac', '.wav'];

const lines = [
  '// Generated by scripts/gen-music.js from assets/music/. Do not edit.',
  'export type Track = { title: string; file: string; source: number };',
  '',
  "export const TRACKS: Record<'city' | 'town' | 'route', Track[]> = {",
];
const counts = [];
for (const kind of KINDS) {
  const dir = path.join(musicDir, kind);
  fs.mkdirSync(dir, { recursive: true });
  const files = fs
    .readdirSync(dir)
    .filter((f) => EXTS.includes(path.extname(f).toLowerCase()))
    .sort();
  counts.push(`${kind} ${files.length}`);
  lines.push(`  ${kind}: [`);
  for (const f of files) {
    const title = path.basename(f, path.extname(f)).replace(/^\d+[\s._-]*/, '');
    const rel = `../../assets/music/${kind}/${f}`;
    lines.push(
      `    { title: ${JSON.stringify(title)}, file: ${JSON.stringify(`${kind}/${f}`)}, source: require(${JSON.stringify(rel)}) },`,
    );
  }
  lines.push('  ],');
}
lines.push('};', '');

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, lines.join('\n'));
console.log(`Music: ${counts.join(', ')}`);
